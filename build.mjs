function banner(target) {
  return '/* GENERATED by build.mjs from ' + target.parts.length + ' fragments under src/ — edit those, not this file. */\n'
}

export function render(target) {
  const bodies = target.parts.map(function (rel) {
    const file = path.join(ROOT, rel)
    if (!fs.existsSync(file)) throw new Error('missing source fragment: ' + rel)
    return fs.readFileSync(file, 'utf8')
  })
  return banner(target) + bodies.join('')
}

export function buildAll(write) {
  const report = []
  for (const target of TARGETS) {
    const next = render(target)
    const file = path.join(ROOT, target.out)
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
    const stale = current !== next
    if (write && stale) fs.writeFileSync(file, next)
    report.push({ out: target.out, stale: stale, bytes: Buffer.byteLength(next) })
  }
  return report
}

const invokedDirectly = process.argv[1] !== undefined && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)
if (invokedDirectly) {
  const check = process.argv.indexOf('--check') >= 0
  const report = buildAll(check !== true)
  let bad = 0
  for (const row of report) {
    const state = row.stale ? (check ? 'STALE' : 'written') : 'current'
    if (check && row.stale) bad += 1
    console.log(row.out.padEnd(12) + state.padEnd(9) + String(row.bytes).padStart(8) + ' bytes')
  }
  if (bad > 0) {
    console.error('build: ' + String(bad) + ' target(s) are not up to date — run `node build.mjs`')
    process.exit(1)
  }
}
